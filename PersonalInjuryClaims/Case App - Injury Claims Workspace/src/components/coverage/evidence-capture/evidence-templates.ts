/**
 * WHAT A SELECTION BECOMES — the reading each part of the record produces.
 *
 * The reader drags across something, types a title, and presses Add. The title is
 * theirs; the description under it is not. This is where the descriptions live.
 *
 * ## The generation is authored, and saying so is the point
 *
 * Nothing here reasons. A section produces the same paragraph every time, keyed by
 * the `data-evidence-source` its markup declares
 * (../../_views/claims-console-v2/app/components/coverage/RecordSections.tsx).
 * That is a deliberate choice for a demo rather than a shortcut waiting to be
 * replaced: a reading that varied with the reader's phrasing would have to be
 * generated by something, and a mock that pretended to vary — reordering clauses,
 * echoing the reader's words back as though it had understood them — is the kind of
 * fake that reads as real on stage and cannot be defended off it. Fixed copy is
 * legible as fixed copy.
 *
 * **The description is grounded in the fixture's own figures.** Six claims in
 * twenty-four months, all approved, none contested, first claim on this policy — all
 * of it is in `history` on the coverage fixture, and the paragraph is a reading OF
 * those rows rather than a slogan beside them. If those numbers change, this
 * paragraph is wrong and has to change with them; that is the cost of authored copy
 * and it is worth paying here.
 *
 * ## What the reader supplies, and what they don't
 *
 * The **title** is typed in the capture bar and used verbatim — it is the one part
 * of the item that says what THIS reader noticed, and generating over the top of it
 * would throw away the only judgement in the gesture.
 *
 * **Importance and the call are set here**, medium and approve, because the reading
 * is what carries them: a claimant in good standing argues for approving, and it
 * argues moderately. They are editable on the row afterwards, which is the point of
 * setting them at all rather than leaving them blank — a default worth overriding
 * beats a blank worth filling.
 *
 * ## Sources stays empty
 *
 * The row's own `addedByReviewer` flag is what marks this as a person's contribution
 * (`EvidenceItem` in
 * ../../_views/claims-console-v2/app/lib/coverage/fixture.ts), and that field's
 * note is explicit that `sources` is empty on an added item whose author did not
 * say. Writing "Reviewer" into it would be putting the same fact in two places, in
 * a field meant for the systems a reading was taken from.
 */

import type { EvidenceCall, Importance } from "@/lib/coverage/fixture";

/** What a source contributes to the item, beyond the title the reader typed. */
export interface EvidenceTemplate {
  /** The generated description. Fixed per source — see the module note. */
  note: string;
  importance: Importance;
  call: EvidenceCall;
}

/**
 * The sources that produce evidence, and what each one says.
 *
 * A section absent from this table raises the bar and commits nothing. That is not
 * an oversight to fill in later: the bar is one widget over the whole record, and a
 * section earns an entry here when somebody has decided what a selection in it
 * MEANS. Inventing a reading for the finding or the documents so the table looks
 * complete would put words in the record that nobody wrote.
 */
export const EVIDENCE_TEMPLATES: Record<string, EvidenceTemplate> = {
  customer: {
    note:
      "Low risk, good standing. Six claims in twenty-four months, all approved and " +
      "none contested; this is the first injury claim on this policy in thirty months " +
      "on cover, and the two prior claims under it were both approved. " +
      "Nothing in the claimant's history argues against approving.",
    importance: "medium",
    call: "approve",
  },
};

/** The reading for a source, or `null` where that source produces none. */
export function templateFor(source: string | null): EvidenceTemplate | null {
  return source ? (EVIDENCE_TEMPLATES[source] ?? null) : null;
}
